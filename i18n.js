function text(value){
  const raw=value.trim();
  if(!raw)return value;
  if(zh.has(raw))return value.replace(raw,zh.get(raw));
  if(status.has(raw))return value.replace(raw,status.get(raw));
  const spaced=raw.replaceAll('_',' '),key=raw.replaceAll(' ','_').toUpperCase();
  if(status.has(key))return value.replace(raw,status.get(key));
  for(const [pattern,replacement] of patterns)if(pattern.test(raw))return value.replace(raw,raw.replace(pattern,replacement));
  let translated=value;
  for(const [from,to] of phrases)translated=translated.replaceAll(from,to);
  return translated;
}

function translate(root=document){
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  for(let node;node=walker.nextNode();)if(!node.parentElement?.closest('nav,script,style')){
    const translated=text(node.nodeValue);
    if(translated!==node.nodeValue)node.nodeValue=translated;
  }
  const elements=root.querySelectorAll?.('[placeholder],[aria-label],[title]')||[];
  for(const element of elements)for(const name of ['placeholder','aria-label','title'])if(element.hasAttribute(name))element.setAttribute(name,text(element.getAttribute(name)));
}

